from typing import TypedDict


class LinkedInState(TypedDict, total=False):

    # --------------------------------------------------------
    # Execution
    # --------------------------------------------------------

    execution_key: str
    execution_status: str

    # --------------------------------------------------------
    # Topic
    # --------------------------------------------------------

    topic: str
    subtopic: str
    angle: str

    # --------------------------------------------------------
    # Research
    # --------------------------------------------------------

    research: str

    # --------------------------------------------------------
    # Generated content
    # --------------------------------------------------------

    generated_post: str

    # --------------------------------------------------------
    # Validation
    # --------------------------------------------------------

    is_ai_ml: bool
    technically_sound: bool
    professional: bool
    recruiter_relevant: bool
    engineer_relevant: bool
    grammar_ok: bool

    quality_score: float
    validation_feedback: str

    # --------------------------------------------------------
    # Duplicate detection
    # --------------------------------------------------------

    is_duplicate: bool
    duplicate_score: float

    # --------------------------------------------------------
    # Retry
    # --------------------------------------------------------

    retry_count: int

    # --------------------------------------------------------
    # LinkedIn
    # --------------------------------------------------------

    linkedin_post_id: str

    # --------------------------------------------------------
    # General
    # --------------------------------------------------------

    status: str